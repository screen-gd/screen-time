'use strict';

// Writes app/dither.css: the dithered textures Tally paints with instead of
// colour. A port of the static-fill part of dithercn's dither-core
// (https://github.com/opencoredev/dithercn, MIT, (c) 2026 Leo and Shadcn Labs):
// Bayer threshold maps, dithered ramps, dotted and hatched tiles, all as
// tiled SVG masks over the ink colour. Run with: bun run dither
const fs = require('node:fs');
const path = require('node:path');

const OUT = path.join(__dirname, '..', 'app', 'dither.css');

// Bayer ranks: interleave the bits of (x xor y) and y, least significant first.
function bayer(size) {
  const thresholds = new Float32Array(size * size);
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      let rank = 0;
      for (let bit = 1; bit < size; bit *= 2) {
        const xBit = Math.floor(x / bit) % 2;
        const yBit = Math.floor(y / bit) % 2;
        rank = rank * 4 + 2 * ((xBit + yBit) % 2) + yBit;
      }
      thresholds[y * size + x] = (rank + 0.5) / (size * size);
    }
  }
  return { size, at: (x, y) => thresholds[(y % size) * size + (x % size)] };
}

const BAYER4 = bayer(4);
const BAYER8 = bayer(8);

// One SVG path covering the inked cells of a grid, in cell units.
function cellsPath(width, height, inked) {
  let d = '';
  for (let y = 0; y < height; y++) {
    let start = -1;
    for (let x = 0; x <= width; x++) {
      const on = x < width && inked(x, y);
      if (on && start === -1) start = x;
      else if (!on && start !== -1) {
        d += `M${start} ${y}h${x - start}v1h${start - x}z`;
        start = -1;
      }
    }
  }
  return d;
}

function svgUrl(width, height, d) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" shape-rendering="crispEdges"><path d="${d}"/></svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}

const cells = (n) => `calc(var(--dither-cell) * ${n})`;

// A flat level: share of cells inked, 0 to 1.
function level(value, map = BAYER4) {
  return { image: svgUrl(map.size, map.size, cellsPath(map.size, map.size, (x, y) => value > map.at(x, y))), size: cells(map.size) };
}

// A ramp: coverage falls from `from` at `edge` to `to` over `length` cells.
// Unioned with the flat `to` level so the far side keeps its texture.
function ramp(edge, length, from, to, map = BAYER4) {
  const along = Math.ceil(length / map.size) * map.size;
  const vertical = edge === 'top' || edge === 'bottom';
  const width = vertical ? map.size : along;
  const height = vertical ? along : map.size;
  const levelAt = (i) => {
    const step = edge === 'top' || edge === 'left' ? i : along - 1 - i;
    return step >= length ? to : from + (to - from) * ((step + 0.5) / length);
  };
  const d = cellsPath(width, height, (x, y) => levelAt(vertical ? y : x) > map.at(x, y));
  const floor = level(to, map);
  const position = { top: 'left top', bottom: 'left bottom', left: 'left top', right: 'right top' }[edge];
  return {
    image: `${svgUrl(width, height, d)}, ${floor.image}`,
    size: `${cells(width)} ${cells(height)}, ${floor.size}`,
    repeat: `${vertical ? 'repeat-x' : 'repeat-y'}, repeat`,
    position: `${position}, ${position}`,
  };
}

// A disc whose tone falls off from the centre: a lamp drawn in dots.
function disc(diameter, core, map = BAYER8) {
  const r = diameter / 2;
  const d = cellsPath(diameter, diameter, (x, y) => {
    const dist = Math.hypot(x + 0.5 - r, y + 0.5 - r) / r;
    const tone = dist <= core ? 1 : Math.max(0, 1 - (dist - core) / (1 - core)) ** 1.6;
    return tone > map.at(x, y);
  });
  return svgUrl(diameter, diameter, d);
}

const DOTTED = { image: svgUrl(4, 4, cellsPath(4, 4, (x, y) => y % 2 === 0 && (x + y / 2) % 2 === 0)), size: cells(4) };
const HATCHED = { image: svgUrl(4, 4, cellsPath(4, 4, (x, y) => (x + y) % 4 === 3)), size: cells(4) };

function flat(name, tex) {
  return `  --d-${name}: ${tex.image};\n  --d-${name}-size: ${tex.size};\n`;
}

function ramped(name, tex) {
  return `  --d-${name}: ${tex.image};\n  --d-${name}-size: ${tex.size};\n  --d-${name}-repeat: ${tex.repeat};\n  --d-${name}-position: ${tex.position};\n`;
}

const css = `/* Generated by scripts/make-dither.js - do not edit by hand.
   Dithered textures used in place of colour, ported from dithercn
   (https://github.com/opencoredev/dithercn, MIT). Each is a tiled mask:
   paint an element with --dither-ink and mask it with one of these. */

:root {
  --dither-cell: 2px;
  --dither-ink: #ececec;

${flat('l88', level(0.88))}${flat('l75', level(0.75))}${flat('l50', level(0.5))}${flat('l25', level(0.25))}${flat('l12', level(0.125))}${flat('dotted', DOTTED)}${flat('hatched', HATCHED)}${ramped('ramp-top', ramp('top', 40, 1, 0.22))}${ramped('ramp-right', ramp('right', 24, 1, 0.5))}${ramped('ramp-left', ramp('left', 10, 0.9, 0))}  --d-lamp: ${disc(14, 0.32)};
  --d-lamp-off: ${disc(14, 0, BAYER4)};
}

/* a flat texture by name, for strips and legends */
.tex { background-color: var(--dither-ink); }
.tex-solid { }
${['l88', 'l75', 'l50', 'l25', 'l12', 'dotted', 'hatched'].map((n) => `.tex-${n} { -webkit-mask: var(--d-${n}) repeat 0 0 / var(--d-${n}-size); mask: var(--d-${n}) repeat 0 0 / var(--d-${n}-size); }`).join('\n')}
`;

fs.writeFileSync(OUT, css);
console.log(`[dither] wrote ${path.relative(process.cwd(), OUT)} (${css.length} bytes)`);
